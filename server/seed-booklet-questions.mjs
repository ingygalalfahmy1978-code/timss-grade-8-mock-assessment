import mysql from "mysql2/promise";

const conn = await mysql.createPool(process.env.DATABASE_URL);

// ─── Get current max question ID ──────────────────────────────────────────────
const [[{ maxId }]] = await conn.query("SELECT COALESCE(MAX(id),0) AS maxId FROM questions");
let nextId = Number(maxId) + 1;

// ─── Get exam IDs ──────────────────────────────────────────────────────────────
const [exams] = await conn.query("SELECT id, name FROM exams ORDER BY id");
const examMap = {};
for (const e of exams) examMap[e.name] = e.id;

console.log("Exams found:", examMap);

// ─── Assign all mocks to both classes (30003 = 8A, 30004 = 8B) ────────────────
const classIds = [30003, 30004];
for (const [name, examId] of Object.entries(examMap)) {
  for (const classId of classIds) {
    const [[existing]] = await conn.query(
      "SELECT id FROM class_exam_assignments WHERE class_id=? AND exam_id=?",
      [classId, examId]
    );
    if (!existing) {
      await conn.query(
        "INSERT INTO class_exam_assignments (class_id, exam_id, is_active, created_at, updated_at) VALUES (?,?,1,NOW(),NOW())",
        [classId, examId]
      );
      console.log(`Assigned ${name} (${examId}) to class ${classId}`);
    } else if (!existing.is_active) {
      await conn.query(
        "UPDATE class_exam_assignments SET is_active=1, updated_at=NOW() WHERE id=?",
        [existing.id]
      );
      console.log(`Re-activated ${name} (${examId}) for class ${classId}`);
    }
  }
}

// ─── Helper to insert a question and add it to an exam ────────────────────────
async function addQuestion(q, examId) {
  const id = nextId++;
  await conn.query(
    `INSERT INTO questions
      (id, subject, content_domain, cognitive_domain, difficulty, question_type,
       question_text, options, correct_answer, explanation, max_points,
       science_sub_domain, session, block_number, created_at, updated_at)
     VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,NOW(),NOW())`,
    [
      id,
      q.subject,
      q.contentDomain,
      q.cognitiveDomain ?? "Knowing",
      q.difficulty ?? "Medium",
      q.questionType ?? "multiple_choice",
      q.questionText,
      q.options ? JSON.stringify(q.options) : null,
      q.correctAnswer,
      q.explanation ?? null,
      q.maxPoints ?? 1,
      q.scienceSubDomain ?? null,
      q.session ?? "math_session",
      q.blockNumber ?? 1,
    ]
  );

  // Get current max order_index for this exam
  const [[{ maxOrd }]] = await conn.query(
    "SELECT COALESCE(MAX(order_index),0) AS maxOrd FROM exam_questions WHERE exam_id=?",
    [examId]
  );
  await conn.query(
    "INSERT INTO exam_questions (exam_id, question_id, order_index, session, block_number, created_at) VALUES (?,?,?,?,?,NOW())",
    [examId, id, Number(maxOrd) + 1, q.session ?? "math_session", q.blockNumber ?? 1]
  );
  return id;
}

